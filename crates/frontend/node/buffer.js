// UTF-8 decoding as node's (WHATWG): an invalid or truncated sequence's maximal subpart is one
// U+FFFD. T80: native for a Uint8Array (a Buffer).
function utf8Slice (buf, start, end) {
  end = Math.min(buf.length, end)
  if (start >= end) return ''
  const kind = __intrinsic_typed_kind(buf)
  if ((kind === 1 || kind === 2) && start >= 0) {
    return __intrinsic_typed_utf8_slice(buf, start, end)
  }
  const res = []

  let i = start
  while (i < end) {
    const b0 = buf[i]
    if (b0 < 0x80) {
      res.push(b0)
      i++
      continue
    }
    let need = 0
    let cp = 0
    let lower = 0x80
    let upper = 0xBF
    if (b0 >= 0xC2 && b0 <= 0xDF) {
      need = 1
      cp = b0 & 0x1F
    } else if (b0 >= 0xE0 && b0 <= 0xEF) {
      need = 2
      cp = b0 & 0xF
      if (b0 === 0xE0) lower = 0xA0
      if (b0 === 0xED) upper = 0x9F
    } else if (b0 >= 0xF0 && b0 <= 0xF4) {
      need = 3
      cp = b0 & 0x7
      if (b0 === 0xF0) lower = 0x90
      if (b0 === 0xF4) upper = 0x8F
    } else {
      res.push(0xFFFD)
      i++
      continue
    }
    let j = i + 1
    let ok = true
    for (let k = 0; k < need; k++, j++) {
      const b = j < end ? buf[j] : -1
      if (b < lower || b > upper) {
        ok = false
        break
      }
      lower = 0x80
      upper = 0xBF
      cp = (cp << 6) | (b & 0x3F)
    }
    if (!ok) {
      res.push(0xFFFD)
      i = j
      continue
    }
    if (cp > 0xFFFF) {
      // encode to utf16 (surrogate pair dance)
      cp -= 0x10000
      res.push(cp >>> 10 & 0x3FF | 0xD800)
      cp = 0xDC00 | cp & 0x3FF
    }
    res.push(cp)
    i = j
  }

  return decodeCodePointsArray(res)
}

// Based on http://stackoverflow.com/a/22747272/680742, the browser with
// the lowest limit is Chrome, with 0x10000 args.
// We go 1 magnitude less, for safety
const MAX_ARGUMENTS_LENGTH = 0x1000

function decodeCodePointsArray (codePoints) {
  const len = codePoints.length
  if (len <= MAX_ARGUMENTS_LENGTH) {
    return String.fromCharCode.apply(String, codePoints) // avoid extra slice()
  }

  // Decode in chunks to avoid "call stack size exceeded".
  let res = ''
  let i = 0
  while (i < len) {
    res += String.fromCharCode.apply(
      String,
      codePoints.slice(i, i += MAX_ARGUMENTS_LENGTH)
    )
  }
  return res
}

