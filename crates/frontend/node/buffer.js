function createBuffer (length) {
  if (length > K_MAX_LENGTH) {
    throw new RangeError('The value "' + length + '" is invalid for option "size"')
  }
  // Return an augmented `Uint8Array` instance
  const buf = new Uint8Array(length)
  Object.setPrototypeOf(buf, Buffer.prototype)
  return buf
}

/**
 * The Buffer constructor returns instances of `Uint8Array` that have their
 * prototype changed to `Buffer.prototype`. Furthermore, `Buffer` is a subclass of
 * `Uint8Array`, so the returned instances will have all the node `Buffer` methods
 * and the `Uint8Array` methods. Square bracket notation works as expected -- it
 * returns a single octet.
 *
 * The `Uint8Array` prototype remains unmodified.
 */

function Buffer (arg, encodingOrOffset, length) {
  // Common case.
  if (typeof arg === 'number') {
    if (typeof encodingOrOffset === 'string') {
      throw $$errInvalidArgType('string', 'of type string', arg)
    }
    return Buffer.alloc(arg)
  }
  return from(arg, encodingOrOffset, length)
}

Buffer.poolSize = 64 * 1024 // not used by this implementation

function from (value, encodingOrOffset, length) {
  if (typeof value === 'string') {
    return fromString(value, encodingOrOffset)
  }
  if (typeof value === 'object' && value !== null) {
    if (isInstance(value, ArrayBuffer)) {
      return fromArrayBuffer(value, encodingOrOffset, length)
    }
    const valueOf = value.valueOf && value.valueOf()
    if (valueOf != null && valueOf !== value && (typeof valueOf === 'string' || typeof valueOf === 'object')) {
      return from(valueOf, encodingOrOffset, length)
    }
    const b = fromObject(value)
    if (b) return b
    if (typeof value[Symbol.toPrimitive] === 'function') {
      const primitive = value[Symbol.toPrimitive]('string')
      if (typeof primitive === 'string') {
        return fromString(primitive, encodingOrOffset)
      }
    }
  }
  const e = new TypeError('The first argument must be of type string or an instance of Buffer, ArrayBuffer, or Array or an Array-like Object. Received ' + $$nodeSpecificType(value))
  e.code = 'ERR_INVALID_ARG_TYPE'
  throw e
}

