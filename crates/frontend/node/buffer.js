// node's validateNumber(value, name, min, max).
function validateNumberRange (value, name, min, max) {
  if (typeof value !== 'number') throw $$errInvalidArgType(name, 'of type number', value)
  if (value < min || value > max || value !== value) {
    throw $$errOutOfRange(name, `>= ${min} && <= ${max}`, value)
  }
}


