function isUtf8 (input) {
  const b = bytesOf(input)
  let i = 0
  while (i < b.length) {
    const c = b[i]
    let n = 0
    let min = 0
    if (c < 0x80) {
      i++
      continue
    } else if (c >= 0xc2 && c <= 0xdf) {
      n = 1
      min = 0x80
    } else if (c >= 0xe0 && c <= 0xef) {
      n = 2
      min = 0x800
    } else if (c >= 0xf0 && c <= 0xf4) {
      n = 3
      min = 0x10000
    } else {
      return false
    }
    let cp = c & (0x3f >> n)
    for (let k = 1; k <= n; k++) {
      const d = b[i + k]
      if (d === undefined || (d & 0xc0) !== 0x80) return false
      cp = (cp << 6) | (d & 0x3f)
    }
    if (cp < min || cp > 0x10ffff || (cp >= 0xd800 && cp <= 0xdfff)) return false
    i += n + 1
  }
  return true
}

