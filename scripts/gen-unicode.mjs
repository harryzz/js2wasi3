#!/usr/bin/env node
// Generates the Unicode data of the RegExp engine (T27) from the node that runs it (the oracle's
// own Unicode version: node 24.21.0 has Unicode 17.0) and the UCD alias / case folding files of
// that version (fetched from unicode.org):
//   crates/lower/builtins/unicode-case.js  the case tables of the `i` flag, always in the prelude
//   crates/lower/src/unicode_props.rs      the `\p{…}` texts node accepts and their code point sets;
//                                          the prelude gets only the ones a program's source names
// Usage: node scripts/gen-unicode.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const VERSION = process.versions.unicode;
const UCD = `https://www.unicode.org/Public/${VERSION}.0/ucd/`;

async function ucd(name) {
  const res = await fetch(UCD + name);
  if (!res.ok) {
    throw new Error(`${UCD}${name}: ${res.status}`);
  }
  return (await res.text()).split("\n").map((l) => l.replace(/#.*/, "").trim()).filter((l) => l);
}

// ---- case tables ---------------------------------------------------------------------------

// Runs `[start, count, delta, stride]` covering a sorted map cp → target.
function runs(entries) {
  const out = [];
  let i = 0;
  while (i < entries.length) {
    const [c, t] = entries[i];
    const delta = t - c;
    let stride = 1;
    if (i + 1 < entries.length && entries[i + 1][1] - entries[i + 1][0] === delta) {
      const s = entries[i + 1][0] - c;
      if (s === 1 || s === 2) {
        stride = s;
      }
    }
    let n = 1;
    while (
      i + n < entries.length &&
      entries[i + n][0] === c + n * stride &&
      entries[i + n][1] - entries[i + n][0] === delta
    ) {
      n++;
    }
    out.push(c, n, delta, stride);
    i += n;
  }
  return out;
}

// Numbers → a JS string: zigzag, then base-0x4000 digits (continuation units 0x4000–0x7FFF, never
// a surrogate), most significant first.
function encode(nums) {
  let s = "";
  for (const v of nums) {
    let z = v < 0 ? -2 * v - 1 : 2 * v;
    const digits = [z % 0x4000];
    z = Math.floor(z / 0x4000);
    while (z > 0) {
      digits.push(0x4000 + (z % 0x4000));
      z = Math.floor(z / 0x4000);
    }
    for (let k = digits.length - 1; k >= 0; k--) {
      const u = digits[k];
      s +=
        u >= 0x20 && u < 0x7f && u !== 0x22 && u !== 0x5c
          ? String.fromCharCode(u)
          : "\\u" + u.toString(16).padStart(4, "0");
    }
  }
  return s;
}

// Canonicalize without `u` (ES2025 22.2.7.3): toUpperCase of one code unit, unless the result
// isn't one code unit or maps a non-ASCII unit to ASCII.
const nonUnicode = [];
for (let u = 0; u < 0x10000; u++) {
  const up = String.fromCharCode(u).toUpperCase();
  if (up.length !== 1) {
    continue;
  }
  const t = up.charCodeAt(0);
  if (t !== u && !(u >= 128 && t < 128)) {
    nonUnicode.push([u, t]);
  }
}
// With `u`: simple case folding (CaseFolding.txt, statuses C and S).
const folding = [];
for (const line of await ucd("CaseFolding.txt")) {
  const [code, status, mapping] = line.split(";").map((f) => f.trim());
  if (status === "C" || status === "S") {
    folding.push([parseInt(code, 16), parseInt(mapping, 16)]);
  }
}
folding.sort((a, b) => a[0] - b[0]);
// Check the folding against node's `iu` matching for every folded character.
for (const [c, t] of folding) {
  const re = new RegExp("^\\u{" + c.toString(16) + "}$", "iu");
  if (!re.test(String.fromCodePoint(t))) {
    throw new Error(`folding ${c.toString(16)} → ${t.toString(16)} disagrees with node`);
  }
}

let caseJs = `// Generated by scripts/gen-unicode.mjs from node ${process.versions.node} (Unicode ${VERSION}): do not edit.
// The case tables of the RegExp engine's \`i\` flag (T27, see regexp.js \`$$reCaseTable\`): runs
// \`[start, count, delta, stride]\` (character start + k * stride maps to itself + delta), encoded as
// zigzag numbers in base-0x4000 code units (continuation units 0x4000–0x7FFF first).

// Canonicalize without \`u\`: toUpperCase of one code unit (${nonUnicode.length} units).
function $$reCaseRunsNonUnicode() {
  return "${encode(runs(nonUnicode))}";
}

// Canonicalize with \`u\`: simple case folding (${folding.length} characters).
function $$reCaseRunsUnicode() {
  return "${encode(runs(folding))}";
}
`;
// String.prototype.toUpperCase / toLowerCase (T87): per code point, node's full (language-insensitive)
// mapping. One code point → one: runs; one → several (SpecialCasing.txt's unconditional ones): a list.
// Σ's Final_Sigma rule is applied by `$$caseMap` with the Cased / Case_Ignorable sets below.
const caseSimple = { upper: [], lower: [] };
const caseSpecial = { upper: [], lower: [] };
for (let c = 0; c <= 0x10ffff; c++) {
  if (c >= 0xd800 && c <= 0xdfff) {
    continue;
  }
  const ch = String.fromCodePoint(c);
  for (const [dir, r] of [["upper", ch.toUpperCase()], ["lower", ch.toLowerCase()]]) {
    const cps = [...r].map((x) => x.codePointAt(0));
    if (cps.length === 1) {
      if (cps[0] !== c) {
        caseSimple[dir].push([c, cps[0]]);
      }
    } else {
      if (cps.length > 3) {
        throw new Error(`${dir} of ${c.toString(16)} has ${cps.length} code points`);
      }
      caseSpecial[dir].push(c, cps.length, cps[0], cps[1] ?? 0, cps[2] ?? 0);
    }
  }
}
// Sorted code point ranges `[lo, hi]` of a binary property.
function propRanges(name) {
  const one = new RegExp("^\\p{" + name + "}$", "u");
  const out = [];
  for (let c = 0; c <= 0x10ffff; c++) {
    if (c >= 0xd800 && c <= 0xdfff) {
      continue;
    }
    if (one.test(String.fromCodePoint(c))) {
      if (out.length && out[out.length - 1] === c - 1) {
        out[out.length - 1] = c;
      } else {
        out.push(c, c);
      }
    }
  }
  return out;
}
const cased = propRanges("Cased");
const caseIgnorable = propRanges("Case_Ignorable");

caseJs += `
// String.prototype.toUpperCase / toLowerCase (T87, string.js \`$$caseMap\`): one code point to one, as runs
// (${caseSimple.upper.length} / ${caseSimple.lower.length} code points).
function $$caseRunsUpper() {
  return "${encode(runs(caseSimple.upper))}";
}

function $$caseRunsLower() {
  return "${encode(runs(caseSimple.lower))}";
}

// One code point to several: \`[code point, n, c1, c2, c3]\` (${caseSpecial.upper.length / 5} / ${caseSpecial.lower.length / 5}).
function $$caseSpecialUpper() {
  return "${encode(caseSpecial.upper)}";
}

function $$caseSpecialLower() {
  return "${encode(caseSpecial.lower)}";
}

// Final_Sigma's sets: \`Cased\` and \`Case_Ignorable\` as ranges \`[lo, hi]\`.
function $$caseCased() {
  return "${encode(cased)}";
}

function $$caseIgnorable() {
  return "${encode(caseIgnorable)}";
}
`;
// String.prototype.normalize (T87): node's full decompositions per code point (Hangul syllables are
// algorithmic), canonical combining classes (UnicodeData.txt), and the primary composites (a canonical
// decomposition of two code points that NFC puts back together).
const decCanon = [];
const decCompat = [];
for (let c = 0; c <= 0x10ffff; c++) {
  if ((c >= 0xd800 && c <= 0xdfff) || (c >= 0xac00 && c <= 0xd7a3)) {
    continue;
  }
  const ch = String.fromCodePoint(c);
  const d = ch.normalize("NFD");
  const kd = ch.normalize("NFKD");
  if (d !== ch) {
    const cps = [...d].map((x) => x.codePointAt(0));
    decCanon.push(c, cps.length, ...cps);
  }
  if (kd !== d) {
    const cps = [...kd].map((x) => x.codePointAt(0));
    decCompat.push(c, cps.length, ...cps);
  }
}
const ccc = [];
const compose = [];
for (const line of await ucd("UnicodeData.txt")) {
  const f = line.split(";");
  const c = parseInt(f[0], 16);
  const cl = +f[3];
  if (cl !== 0) {
    if (ccc.length && ccc[ccc.length - 2] === c - 1 && ccc[ccc.length - 1] === cl) {
      ccc[ccc.length - 2] = c;
    } else {
      ccc.push(c, c, cl);
    }
  }
  if (f[5] && !f[5].startsWith("<")) {
    const parts = f[5].split(" ").map((x) => parseInt(x, 16));
    if (parts.length === 2 && String.fromCodePoint(...parts).normalize("NFC") === String.fromCodePoint(c)) {
      compose.push([parts[0], parts[1], c]);
    }
  }
}
// The ranges above are [lo, hi, class] triples, merged only for equal classes (the line above wrote
// [lo, hi, cl] with lo patched): rebuild them from the flat list.
const cccRanges = [];
for (let i = 0; i < ccc.length; i += 3) {
  cccRanges.push(ccc[i], ccc[i + 1], ccc[i + 2]);
}
compose.sort((a, b) => a[0] - b[0] || a[1] - b[1]);

caseJs += `
// String.prototype.normalize (T87, string.js \`$$normalize\`): full decompositions \`[code point, n, c1…cn]\`
// (canonical: ${decCanon.length} numbers; compatibility where it differs: ${decCompat.length}), canonical combining
// classes \`[lo, hi, class]\` (${cccRanges.length / 3} ranges) and primary composites \`[a, b, composite]\`
// (${compose.length}). Hangul syllables are algorithmic.
function $$normDecompCanon() {
  return "${encode(decCanon)}";
}

function $$normDecompCompat() {
  return "${encode(decCompat)}";
}

function $$normCombiningClasses() {
  return "${encode(cccRanges)}";
}

function $$normComposites() {
  return "${encode(compose.flat())}";
}
`;
writeFileSync(join(ROOT, "crates/lower/builtins/unicode-case.js"), caseJs);

// ---- property escapes ----------------------------------------------------------------------

// The code points below and above the surrogates, in order (the surrogates are tested one by one):
// runs of a property are the matches of `\p{…}+`.
let low = "";
for (let c = 0; c < 0xd800; c++) {
  low += String.fromCharCode(c);
}
let high = "";
for (let c = 0xe000; c <= 0x10ffff; c++) {
  high += String.fromCodePoint(c);
}

function ranges(text) {
  const re = new RegExp("\\p{" + text + "}+", "gu");
  const one = new RegExp("^\\p{" + text + "}$", "u");
  const out = [];
  const add = (lo, hi) => {
    if (out.length && out[out.length - 1] + 1 === lo) {
      out[out.length - 1] = hi;
    } else {
      out.push(lo, hi);
    }
  };
  const scan = (s) => {
    for (const m of s.matchAll(re)) {
      const lo = m[0].codePointAt(0);
      const last = m[0].length - (m[0].codePointAt(m[0].length - 2) > 0xffff ? 2 : 1);
      add(lo, m[0].codePointAt(last));
    }
  };
  scan(low);
  for (let u = 0xd800; u <= 0xdfff; u++) {
    if (one.test(String.fromCharCode(u))) {
      add(u, u);
    }
  }
  scan(high);
  for (let i = 1; i < out.length; i++) {
    if (out[i] < out[i - 1]) {
      throw new Error(`${text}: ranges out of order`);
    }
  }
  return out;
}

function valid(text) {
  try {
    new RegExp("\\p{" + text + "}", "u");
    return true;
  } catch {
    return false;
  }
}

// Candidate names from the UCD aliases; kept when node accepts them.
const binary = [];
for (const line of await ucd("PropertyAliases.txt")) {
  const names = line.split(";").map((f) => f.trim());
  if (valid(names[0])) {
    binary.push(names.filter(valid));
  }
}
binary.push(["Any"], ["ASCII"], ["Assigned"]);
const values = { gc: [], sc: [] };
for (const line of await ucd("PropertyValueAliases.txt")) {
  const f = line.split(";").map((x) => x.trim());
  if (f[0] === "gc" || f[0] === "sc") {
    values[f[0]].push(f.slice(1));
  }
}

const texts = new Map(); // accepted text → table index
const tables = [];
const tableOf = new Map(); // canonical text → table index
function add(canonical, names) {
  if (!valid(canonical)) {
    return;
  }
  let t = tableOf.get(canonical);
  if (t === undefined) {
    t = tables.length;
    tables.push(ranges(canonical));
    tableOf.set(canonical, t);
  }
  for (const n of names) {
    if (valid(n) && !texts.has(n)) {
      texts.set(n, t);
    }
  }
}
for (const names of binary) {
  add(names[0], names);
}
for (const vals of values.gc) {
  const names = [];
  for (const v of vals) {
    names.push(v, "gc=" + v, "General_Category=" + v);
  }
  add("gc=" + vals[0], names);
}
for (const [prop, long] of [["sc", "Script"], ["scx", "Script_Extensions"]]) {
  for (const vals of values.sc) {
    const names = [];
    for (const v of vals) {
      names.push(prop + "=" + v, long + "=" + v);
    }
    add(prop + "=" + vals[0], names);
  }
}

const quote = (s) => JSON.stringify(s);
let rs = `//! Generated by scripts/gen-unicode.mjs from node ${process.versions.node} (Unicode ${VERSION}): do not edit.
//! The \`\\p{…}\` texts node accepts (${texts.size}) and their code point sets (${tables.length}), for the
//! RegExp engine (T27): a program's prelude gets the ones its source names ([\`crate::builtins\`]).

/// Accepted \`\\p{…}\` texts, sorted, each with its set's index in [\`TABLES\`].
pub static NAMES: &[(&str, u16)] = &[\n`;
for (const [n, t] of [...texts].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))) {
  rs += `    (${quote(n)}, ${t}),\n`;
}
rs += `];

/// Code point sets as sorted inclusive ranges \`[lo, hi, lo, hi, …]\`.
pub static TABLES: &[&[u32]] = &[\n`;
for (const t of tables) {
  rs += `    &[${t.join(", ")}],\n`;
}
rs += "];\n";
writeFileSync(join(ROOT, "crates/lower/src/unicode_props.rs"), rs);
console.log(
  `unicode ${VERSION}: ${nonUnicode.length} non-u case units, ${folding.length} foldings, ` +
    `${texts.size} property texts, ${tables.length} sets, ${tables.reduce((n, t) => n + t.length / 2, 0)} ranges`,
);
