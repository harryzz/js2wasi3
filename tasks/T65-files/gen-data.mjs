// T65: node 24's constants for the load-only built-ins, as `crates/frontend/node/builtin_data.js`.
// Run with node 24.21.0 (TOOLS.md): node tasks/T65-files/gen-data.mjs > crates/frontend/node/builtin_data.js
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const http = require("http"), http2 = require("http2"), tls = require("tls"), dns = require("dns");
const zlib = require("zlib"), perf = require("perf_hooks"), mod = require("module");
const j = (v) => JSON.stringify(v);
const data = {
  httpMethods: http.METHODS,
  statusCodes: http.STATUS_CODES,
  maxHeaderSize: http.maxHeaderSize,
  http2Constants: http2.constants,
  http2DefaultSettings: http2.getDefaultSettings(),
  tlsDefaultCiphers: tls.DEFAULT_CIPHERS,
  tlsCiphers: tls.getCiphers(),
  dnsCodes: Object.fromEntries(Object.entries(dns).filter(([k, v]) => typeof v === "string")),
  dnsFlags: { ADDRCONFIG: dns.ADDRCONFIG, ALL: dns.ALL, V4MAPPED: dns.V4MAPPED },
  zlibConstants: zlib.constants,
  perfConstants: perf.constants,
  builtinModules: mod.builtinModules,
};
let s = `// node ${process.version}'s constants for the load-only built-ins (T65), generated by\n`;
s += `// tasks/T65-files/gen-data.mjs: don't edit by hand.\n"use strict";\n\n`;
for (const [k, v] of Object.entries(data)) s += `exports.${k} = ${j(v)};\n`;
process.stdout.write(s);
